"""Efficiency of the held-out set, per workflow x condition. Descriptive (SQ3). Read-only.

    python scripts/efficiency_heldout.py --set-name heldout-v1 [--out docs/RESULTS_HELDOUT_efficiency.md]

Not pre-registered and not confirmatory. A descriptive cost comparison only.

Per run, from calls.jsonl, following the accounting rule in docs/freeze_notes.md:
    - every attempt counts, including stream_failed attempts (those tokens were billed)
    - the model_resolution_probe is excluded (infrastructure, not experimental work)
    - output tokens include reasoning tokens; reasoning is not added on top
    calls      model-call attempts, excluding the probe
    runtime    manifest created_utc to the last call record's timestamp, in minutes.
               Runs within a round ran in parallel (up to 7 at once), so this is
               per-run elapsed time, not a share of the grid's wall time.
    cost       input x $2 / 1M + output x $10 / 1M (author-specified rates)

Runs: the completed runs in the set's ledger (status "ok"). Attempts that never
reached the gate (technical failures, re-run in position under pre-registration
section 3) were billed too. They are reported separately as overhead, not
folded into the per-run means.
"""

import argparse
import json
import sys
from datetime import datetime
from pathlib import Path
from statistics import mean

REPO_ROOT = Path(__file__).resolve().parent.parent
RUNS_ROOT = REPO_ROOT / "runs"

TEMPLATE_WORKFLOWS = [
    "P2P-TWM-01", "P2P-PRE-01", "P2P-EXR-01",
    "R2R-ACR-01", "R2R-FSP-01",
    "FPA-VAR-01", "FPA-ABB-01",
]
CONDITIONS = ["council", "baseline"]
PROBE_ROLE = "model_resolution_probe"
PRICE_INPUT_PER_M = 2.0
PRICE_OUTPUT_PER_M = 10.0


def parse_utc(text: str) -> datetime:
    return datetime.fromisoformat(text.replace("Z", "+00:00"))


def cost(input_tokens: int, output_tokens: int) -> float:
    return input_tokens * PRICE_INPUT_PER_M / 1e6 + output_tokens * PRICE_OUTPUT_PER_M / 1e6


def run_figures(run_dir: Path) -> dict:
    manifest = json.loads((run_dir / "run_manifest.json").read_text())
    records = [json.loads(l) for l in (run_dir / "calls.jsonl").read_text().splitlines() if l.strip()]
    work = [r for r in records if r["agent_role"] != PROBE_ROLE]
    end = parse_utc(records[-1]["timestamp_utc"]) if records else parse_utc(manifest["created_utc"])
    return {
        "input": sum(r["input_tokens"] for r in work),
        "output": sum(r["output_tokens"] or 0 for r in work),
        "calls": len(work),
        "failed_attempts": sum(1 for r in work if r.get("attempt_status", "ok") != "ok"),
        "minutes": (end - parse_utc(manifest["created_utc"])).total_seconds() / 60,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--set-name", required=True)
    parser.add_argument("--runs-root", type=Path, default=RUNS_ROOT)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args()

    ledger = args.runs_root / f"_set-{args.set_name}.ledger.jsonl"
    events = [json.loads(l) for l in ledger.read_text().splitlines() if l.strip()]
    finished = [e for e in events if e["event"] == "finished"]

    cells: dict[tuple[str, str], list[dict]] = {}
    for e in finished:
        if e["status"] == "ok":
            cells.setdefault((e["workflow_id"], e["condition"]), []).append(
                run_figures(args.runs_root / e["run_id"]))

    overhead = [run_figures(args.runs_root / e["run_id"]) | {"condition": e["condition"]}
                for e in finished
                if e["status"] != "ok" and e["run_id"] and (args.runs_root / e["run_id"]).exists()]

    out = []
    add = out.append
    add(f"# Held-out efficiency (descriptive, SQ3): set `{args.set_name}`")
    add("")
    add("Generated by `scripts/efficiency_heldout.py` from the run logs. **Descriptive only, "
        "not pre-registered.** Every attempt counts, the resolution probe is excluded, and "
        "output includes reasoning tokens (freeze_notes.md accounting rule). Cost uses the "
        f"author-specified rates: ${PRICE_INPUT_PER_M:.0f}/M input, "
        f"${PRICE_OUTPUT_PER_M:.0f}/M output. Runtime is per-run elapsed time. Runs in a "
        "round shared the API concurrently (up to 7 at once).")
    add("")
    add("## Per workflow x condition (means per completed run)")
    add("")
    add("| Workflow | Condition | n | Input tokens | Output tokens | Calls | Runtime (min) | Cost per run (USD) |")
    add("|---|---|---:|---:|---:|---:|---:|---:|")
    for wf in TEMPLATE_WORKFLOWS:
        for cond in CONDITIONS:
            runs = cells.get((wf, cond), [])
            if not runs:
                continue
            add(f"| {wf} | {cond} | {len(runs)} | {mean(r['input'] for r in runs):,.0f} | "
                f"{mean(r['output'] for r in runs):,.0f} | {mean(r['calls'] for r in runs):.1f} | "
                f"{mean(r['minutes'] for r in runs):.1f} | "
                f"{mean(cost(r['input'], r['output']) for r in runs):.2f} |")
    add("")

    add("## Totals per condition (completed runs)")
    add("")
    add("| Condition | Runs | Input tokens | Output tokens | Calls | Stream-failed attempts "
        "| Mean runtime (min) | Total cost (USD) | Mean cost per run (USD) |")
    add("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    totals = {}
    for cond in CONDITIONS:
        runs = [r for (wf, c), rs in cells.items() if c == cond for r in rs]
        i, o = sum(r["input"] for r in runs), sum(r["output"] for r in runs)
        totals[cond] = cost(i, o)
        add(f"| {cond} | {len(runs)} | {i:,} | {o:,} | {sum(r['calls'] for r in runs):,} | "
            f"{sum(r['failed_attempts'] for r in runs)} | {mean(r['minutes'] for r in runs):.1f} | "
            f"{cost(i, o):,.2f} | {cost(i, o) / len(runs):.2f} |")
    if totals.get("baseline"):
        add("")
        add(f"Council-to-baseline total cost ratio: {totals['council'] / totals['baseline']:.1f}x.")
    add("")

    add("## Overhead: technical-failure attempts (never reached the gate)")
    add("")
    if overhead:
        i, o = sum(r["input"] for r in overhead), sum(r["output"] for r in overhead)
        by_cond = {c: sum(1 for r in overhead if r["condition"] == c) for c in CONDITIONS}
        add(f"{len(overhead)} attempts ({by_cond['council']} council, {by_cond['baseline']} "
            f"baseline) were stopped by an exhausted API credit balance. They were billed, but "
            f"are excluded from the per-run figures above: input {i:,}, output {o:,}, cost "
            f"${cost(i, o):,.2f} at the same rates.")
    else:
        add("None.")
    add("")

    text = "\n".join(out) + "\n"
    if args.out:
        args.out.write_text(text)
        print(f"wrote {args.out}")
    else:
        print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main())
