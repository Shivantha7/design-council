"""Write the step-classification review for the productivity analysis. Read-only on runs.

    python scripts/productivity_classification_review.py --set-name heldout-v1 \
        --out docs/PRODUCTIVITY_CLASSIFICATION_REVIEW.md

Applies design_council/measures/actor_class.py to every step of the seven
held-out encodings and of every completed council TSS (docs/PRODUCTIVITY_METHOD.md
section 2; the baseline is excluded per section 1). It prints the rules, the
global decisions the rules depend on, and every flagged step, for the author's
decisions BEFORE any productivity figure is computed. No PI is computed here.
"""

import argparse
import collections
import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

from design_council.measures import actor_class as ac  # noqa: E402

RUNS_ROOT = REPO_ROOT / "runs"
TEMPLATE_WORKFLOWS = [
    "P2P-TWM-01", "P2P-PRE-01", "P2P-EXR-01",
    "R2R-ACR-01", "R2R-FSP-01",
    "FPA-VAR-01", "FPA-ABB-01",
]
FLAG_TEXT = {
    "G1": "deterministic automation, no AI term",
    "G2": "person performs, automation assists",
    "G3": "person owns policy only",
    "A1": "exception cue and review/assist cue both present",
    "A2": "alternatives or conditional lanes",
    "A3": "actor human, description mentions AI/agent",
    "A4": "automation term may not be the performer",
}
PER_STEP_FLAGS = {"A1", "A2", "A3", "A4"}


def md(text: str) -> str:
    return text.replace("|", "/").replace("\n", " ")


def ai_sentence(description: str) -> str:
    for sentence in re.split(r"(?<=[.;])\s+", description):
        if ac.AI_TERMS.search(sentence):
            return sentence.strip()[:220]
    return ""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--set-name", required=True)
    parser.add_argument("--runs-root", type=Path, default=RUNS_ROOT)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()

    events = [json.loads(l) for l in
              (args.runs_root / f"_set-{args.set_name}.ledger.jsonl").read_text().splitlines()]
    paths = next(e for e in events if e["event"] == "set_started")["workflows"]
    council = {wf: [] for wf in TEMPLATE_WORKFLOWS}
    for e in events:
        if e["event"] == "finished" and e["status"] == "ok" and e["condition"] == "council":
            council[e["workflow_id"]].append(e["run_id"])

    steps = []  # (workflow, source, key, step dict, classification)
    for wf in TEMPLATE_WORKFLOWS:
        for s in json.loads((REPO_ROOT / paths[wf]).read_text())["steps"]:
            steps.append((wf, "original", f"{wf}:{s['step_id']}", s, ac.classify(s["actor"], s["description"])))
        for run_id in council[wf]:
            for s in json.loads((args.runs_root / run_id / "tss.json").read_text())["steps"]:
                steps.append((wf, "council", f"{run_id[-4:]}:{s['step_id']}", s,
                              ac.classify(s["actor"], s["description"])))

    out = []
    add = out.append
    add("# Productivity analysis: step-classification review")
    add("")
    add("**For the author's decisions before any productivity figure is computed** "
        "(docs/PRODUCTIVITY_METHOD.md section 2, committed in `a67c2af`). Exploratory. "
        "No PI has been computed. Generated by "
        "`scripts/productivity_classification_review.py` using "
        "`design_council/measures/actor_class.py`.")
    add("")
    orig = [x for x in steps if x[1] == "original"]
    tss = [x for x in steps if x[1] == "council"]
    add(f"Scope: {len(orig)} original steps (7 held-out encodings) and {len(tss)} target "
        f"steps in {sum(len(v) for v in council.values())} council TSSs. Baseline runs "
        "are excluded (section 1). Each step key is `<workflow>:<step>` for originals and "
        "`<last 4 chars of run id>:<step>` for council steps.")
    add("")

    add("## 1. Rules")
    add("")
    add("Applied to the actor field in this order (the description is used only to raise "
        "flag A3):")
    add("")
    add("| Rule | Condition | Class |")
    add("|---|---|---|")
    add("| pre | remove \"distinct from …\" / \"independent of …\" clauses (segregation, not performer) | – |")
    add("| R1 | no automation term in the actor, once conventional-tool qualifiers (\"ERP\", "
        "\"ERP matching engine\", \"ERP retrieval\", \"ERP automation\") are set aside | HUMAN |")
    add("| R2 | automation term, and the named person handles only exceptions, fallbacks or "
        "flagged items | AGENT |")
    add("| R3 | automation term, and the person is assisted by it or reviews, approves, "
        "confirms, oversees or signs off its work | HYBRID |")
    add("| R4 | automation term and no person in a performing or reviewing role (including "
        "policy-owner-only, see G3) | AGENT |")
    add("")
    add("Term lists (regular expressions, verbatim from the code):")
    add("")
    for name in ["AI_TERMS", "AUTOMATION_TERMS", "CONVENTIONAL", "EXCEPTION_TERMS", "ASSIST_TERMS",
                 "REVIEW_TERMS", "POLICY_OWNER_ONLY", "ALTERNATIVES", "SEGREGATION_CLAUSE",
                 "NON_PERFORMER", "APPROVAL_STEP"]:
        add(f"- `{name}`: `{getattr(ac, name).pattern}`")
    add("")
    add("**Original encodings.** Section 3 sets H_original = 1, with every original step "
        "HUMAN unless the encoding states agent automation. Result: "
        f"{sum(1 for x in orig if x[4].cls == ac.HUMAN)} of {len(orig)} original steps are HUMAN. "
        "No held-out encoding states agent automation. Three carry ERP qualifiers, treated "
        "as conventional tools.")
    add("")
    counts = collections.Counter(x[4].cls for x in tss)
    add(f"**Council steps under the default rules:** HUMAN {counts['HUMAN']}, "
        f"HYBRID {counts['HYBRID']}, AGENT {counts['AGENT']}.")
    add("")

    add("## 2. Global decisions (each changes many steps)")
    add("")

    def group(flag):
        return [x for x in tss if flag in x[4].flags]

    decisions = [
        ("G1", "Does deterministic automation (rules engine, matching engine, pipeline, "
               "\"system-executed\") count as an AI agent?",
         "Default: **yes**. These steps are classed HYBRID or AGENT like AI-agent steps. If "
         "**no**, they become HUMAN (conventional tools, like the ERP in section 2). This "
         "probably moves PI more than any parameter."),
        ("G2", "When the person is the primary performer and an agent or automation only "
               "**assists** (\"supported by\", \"-assisted\", \"with … engine\"), is the step "
               "HYBRID?",
         "Default: **HYBRID**. Section 2 defines HYBRID as an agent performing with a "
         "person reviewing. Alternative: HUMAN, if assistance without agent performance does "
         "not qualify."),
        ("G3", "When the person only **owns or governs the policy** that the automation "
               "applies (no per-item review), is the step AGENT or HYBRID?",
         "Default: **AGENT**. Alternative: HYBRID."),
    ]
    for flag, question, note in decisions:
        affected = group(flag)
        add(f"### {flag}. {question}")
        add("")
        add(note)
        add("")
        add(f"Affected council steps: **{len(affected)}**. Distinct actor strings:")
        add("")
        for actor, n in collections.Counter(x[3]["actor"] for x in affected).most_common():
            cls = next(x[4].cls for x in affected if x[3]["actor"] == actor)
            add(f"- {cls} ×{n}: {md(actor)}")
        add("")
    add("### G4. Section 5 counting definitions")
    add("")
    add("- **Actor hand-off**: consecutive steps (in the encoding's or TSS's step order) "
        "whose actors differ. Default: compare the **base role**, the actor text before the "
        "first \"(\", \",\" or \";\", case-folded, so \"GL accountant\" → \"GL accountant "
        "(preparer)\" is not a hand-off. Alternative: compare the full actor string.")
    add("- **Human-to-human hand-off**: a hand-off between two steps both classed HUMAN.")
    add("- **Approval step**: the step name matches `APPROVAL_STEP` (approv-, authoris-/-z-, "
        "sign-off, attest-, certif-). Names with \"release\", \"review\" or \"lock\" are "
        "**not** counted by default. The candidates are listed in section 4.")
    add("- **Human-in-the-loop checkpoints** = HYBRID steps + approval steps, with a step "
        "that is both counted once.")
    add("")

    add("## 3. Per-step ambiguities (flags A1–A4)")
    add("")
    add("Each needs a decision: keep the default class, or override. A3 rows show the "
        "description sentence that mentions AI or an agent.")
    add("")
    add("| Key | Workflow | Actor | Default | Rule | Flags | Note |")
    add("|---|---|---|---|---|---|---|")
    flagged = [x for x in tss if PER_STEP_FLAGS & set(x[4].flags)]
    for wf, _, key, s, c in flagged:
        note = ai_sentence(s["description"]) if "A3" in c.flags else ""
        add(f"| {key} | {wf} | {md(s['actor'])[:200]} | {c.cls} | {c.rule} | "
            f"{', '.join(f for f in c.flags)} | {md(note)} |")
    add("")
    add(f"{len(flagged)} council steps carry a per-step flag. Flag meanings: "
        + "; ".join(f"{k} = {v}" for k, v in FLAG_TEXT.items()) + ".")
    add("")

    add("## 4. Approval-step candidates")
    add("")
    add("| Key | Step name | Counted by default? |")
    add("|---|---|---|")
    for wf, src, key, s, c in steps:
        name = s["name"]
        counted = ac.is_approval_step(name)
        borderline = re.search(r"\b(release|review|lock|sign|confirm)\w*\b", name, re.IGNORECASE)
        if counted or borderline:
            add(f"| {key} | {md(name)} | {'yes' if counted else 'no (borderline)'} |")
    add("")

    add("## 5. Full classification (council steps, by distinct actor string)")
    add("")
    add("<details><summary>All distinct council actor strings with default class</summary>")
    add("")
    add("| Class | Rule | Flags | Steps | Actor |")
    add("|---|---|---|---:|---|")
    by_actor = collections.defaultdict(list)
    for x in tss:
        by_actor[x[3]["actor"]].append(x)
    for actor, xs in sorted(by_actor.items(), key=lambda kv: (kv[1][0][4].cls, kv[0])):
        c = xs[0][4]
        add(f"| {c.cls} | {c.rule} | {', '.join(c.flags) or '–'} | {len(xs)} | {md(actor)[:220]} |")
    add("")
    add("</details>")
    add("")

    args.out.write_text("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(orig)} original, {len(tss)} council steps; "
          f"default HUMAN {counts['HUMAN']} HYBRID {counts['HYBRID']} AGENT {counts['AGENT']}; "
          f"G1 {len(group('G1'))}, G2 {len(group('G2'))}, G3 {len(group('G3'))}, "
          f"per-step flagged {len(flagged)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
