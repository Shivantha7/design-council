"""Report transformation depth for one or more runs.

    python scripts/measure_depth.py <encoding.json> <run_dir> [<run_dir> ...] [--markdown]

Reads each run's tss.json and computes the pre-registered depth measure plus
the supplementary descriptives. No API calls; nothing in a run directory is
modified. With --markdown, writes depth.md into each run directory.

The primary and supplementary blocks are printed separately and labelled,
because only the first is pre-registered.
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from design_council.measures.depth import DepthReport, measure_depth  # noqa: E402
from design_council.schemas import (  # noqa: E402
    Disposition,
    TargetStateSpec,
    WorkflowEncoding,
)

DEPTH_FILENAME = "depth.md"
TSS_FILENAME = "tss.json"


def load_report(encoding: WorkflowEncoding, run_dir: Path) -> DepthReport:
    path = run_dir / TSS_FILENAME
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; is {run_dir} a completed run?")

    return measure_depth(encoding, TargetStateSpec.model_validate_json(path.read_text()))


def condition_of(run_dir: Path) -> str:
    """Read the condition from the manifest, for column labels."""
    manifest = run_dir / "run_manifest.json"
    if manifest.exists():
        return json.loads(manifest.read_text()).get("condition", run_dir.name)

    return run_dir.name


def render_text(
    encoding: WorkflowEncoding, reports: dict[str, DepthReport]
) -> list[str]:
    labels = list(reports)
    width = max(12, *(len(label) for label in labels))

    def row(name: str, values: list[str]) -> str:
        return f"  {name:34}" + "".join(v.rjust(width + 2) for v in values)

    lines = [
        f"workflow: {encoding.workflow_id}   baseline steps: {len(encoding.steps)}",
        "",
        "=" * 78,
        "PRIMARY MEASURE (pre-registered)",
        "=" * 78,
        "",
        row("", labels),
        "  " + "-" * (34 + (width + 2) * len(labels)),
    ]

    for disposition in Disposition:
        counts = []
        for label in labels:
            profile = reports[label].profile
            count = profile.count(disposition)
            counts.append(f"{count} ({profile.proportions[disposition.value]:.2f})")
        lines.append(row(f"{disposition.value}", counts))

    lines += [
        "  " + "-" * (34 + (width + 2) * len(labels)),
        row(
            "depth_score (not retained)",
            [f"{reports[label].depth_score:.4f}" for label in labels],
        ),
        "",
        "=" * 78,
        "SUPPLEMENTARY DESCRIPTIVES (not pre-registered; exploratory only)",
        "=" * 78,
        "",
    ]

    supplementary_rows = [
        ("actor_reassignments", lambda s: str(s.actor_reassignments)),
        ("net_new_steps", lambda s: str(s.net_new_steps)),
        ("target_step_count", lambda s: str(s.target_step_count)),
        ("step_count_delta", lambda s: f"{s.step_count_delta:+d}"),
        ("mean_fan_out", lambda s: f"{s.mean_fan_out:.3f}"),
    ]
    for name, render in supplementary_rows:
        lines.append(
            row(name, [render(reports[label].supplementary) for label in labels])
        )

    lines += [
        "",
        "  These descriptives support qualitative analysis only. They were not",
        "  pre-registered and must not be reported as confirmatory findings.",
    ]

    return lines


def render_markdown(encoding: WorkflowEncoding, label: str, report: DepthReport) -> str:
    profile = report.profile
    supplementary = report.supplementary

    lines = [
        f"# {encoding.workflow_id} — transformation depth ({label})",
        "",
        "> Generated by `scripts/measure_depth.py` from `tss.json`. Regenerate "
        "rather than edit.",
        "",
        "## Primary measure (pre-registered)",
        "",
        "| Disposition | Count | Proportion |",
        "| --- | ---: | ---: |",
    ]
    for disposition in Disposition:
        lines.append(
            f"| {disposition.value} | {profile.count(disposition)} | "
            f"{profile.proportions[disposition.value]:.2f} |"
        )

    lines += [
        "",
        f"**depth_score** (proportion of baseline steps not retained): "
        f"**{report.depth_score:.4f}**",
        "",
        "## Supplementary descriptives (not pre-registered)",
        "",
        "> Exploratory only, for qualitative analysis. Not confirmatory.",
        "",
        "| Descriptive | Value |",
        "| --- | ---: |",
        f"| actor_reassignments | {supplementary.actor_reassignments} |",
        f"| net_new_steps | {supplementary.net_new_steps} |",
        f"| target_step_count | {supplementary.target_step_count} |",
        f"| step_count_delta | {supplementary.step_count_delta:+d} |",
        f"| mean_fan_out | {supplementary.mean_fan_out:.3f} |",
        "",
    ]
    if supplementary.actor_reassignment_ids:
        lines += [
            "Baseline steps whose actor changed: "
            + ", ".join(f"`{i}`" for i in supplementary.actor_reassignment_ids),
            "",
        ]
    if supplementary.net_new_step_ids:
        lines += [
            "Target steps with no baseline trace: "
            + ", ".join(f"`{i}`" for i in supplementary.net_new_step_ids),
            "",
        ]

    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("encoding", type=Path)
    parser.add_argument("run_dirs", type=Path, nargs="+")
    parser.add_argument("--markdown", action="store_true")
    args = parser.parse_args(argv)

    with args.encoding.open() as handle:
        encoding = WorkflowEncoding.model_validate(json.load(handle))

    reports: dict[str, DepthReport] = {}
    for index, run_dir in enumerate(args.run_dirs):
        label = condition_of(run_dir)
        if label in reports:
            label = f"{label}#{index + 1}"
        reports[label] = load_report(encoding, run_dir)

    for line in render_text(encoding, reports):
        print(line)

    if args.markdown:
        print()
        for run_dir, (label, report) in zip(args.run_dirs, reports.items()):
            path = run_dir / DEPTH_FILENAME
            path.write_text(render_markdown(encoding, label, report))
            print(f"wrote {path}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
